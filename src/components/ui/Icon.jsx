export default function Icon({ name, size = 16, className, ...rest }) {
  const entry = paths[name];
  if (!entry) return null;

  const common = {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    className,
    'aria-hidden': 'true',
    focusable: 'false',
    ...rest,
  };

  if (entry.solid) {
    return (
      <svg {...common} fill="currentColor">
        <path d={entry.d} />
      </svg>
    );
  }

  return (
    <svg {...common} {...STROKE}>
      {entry.d.split(' M').map((seg, i) => (
        <path key={i} d={i === 0 ? seg : `M${seg}`} />
      ))}
    </svg>
  );
}

/** Career start — drives the auto-computed tenure so it never goes stale. */
export const CAREER_START = new Date(2024, 6, 1); // July 2024

export function tenure(from = CAREER_START, to = new Date()) {
  const months = (to.getFullYear() - from.getFullYear()) * 12 + (to.getMonth() - from.getMonth());
  const y = Math.floor(months / 12);
  const m = months % 12;
  if (y === 0) return `${m} mo`;
  return m === 0 ? `${y} yr` : `${y} yr ${m} mo`;
}

